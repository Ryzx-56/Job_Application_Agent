/**
 * Generates src/components/landing/logo-paths.ts from simple-icons.
 *
 * WHY A BUILD STEP AND NOT A RUNTIME IMPORT: simple-icons ships 3,400+ icons.
 * Importing it from a client component risks pulling far more than the dozen
 * marks this page uses into the landing bundle, and the landing bundle is
 * already the thing hurting mobile performance. This writes the handful of
 * 24x24 path strings we actually use into a plain module, so simple-icons
 * stays a devDependency and ships nothing.
 *
 * Re-run with:  node scripts/generate-logo-paths.mjs
 *
 * Every mark here is CC0 from simple-icons. A company is only listed on the
 * marquee if it has a real mark — there is no drawn-from-memory fallback and
 * no monogram tile, because an approximated wordmark is both a worse
 * trademark position and worse design than leaving the company out.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import * as si from "simple-icons";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "../src/components/landing/logo-paths.ts");

/** Keys into simple-icons, in the order they appear on the marquee. */
const WANTED = [
  "siSaudia",
  "siSap",
  "siSiemens",
  "siAccenture",
  "siEricsson",
  "siNokia",
  "siCisco",
  "siHuawei",
  "siSamsung",
  "siGoogle",
  "siApple",
  "siNvidia",
  "siSnapchat",
  "siShell",
];

const missing = WANTED.filter((k) => !si[k]);
if (missing.length) {
  console.error("Not in simple-icons:", missing.join(", "));
  process.exit(1);
}

const entries = WANTED.map((key) => {
  const icon = si[key];
  return `  { slug: ${JSON.stringify(icon.slug)}, title: ${JSON.stringify(icon.title)}, path: ${JSON.stringify(icon.path)} },`;
}).join("\n");

writeFileSync(
  OUT,
  `// GENERATED by scripts/generate-logo-paths.mjs — do not edit by hand.
// Source: simple-icons (CC0-1.0). Re-run the script to add or update a mark.
//
// Each \`path\` is the icon's outline in a 24x24 viewBox. Rendered in
// currentColor rather than the brand hex: this is a row of contexts, not a
// row of endorsements, and fourteen brand colours on a dark page is noise.

export type BrandLogo = { slug: string; title: string; path: string };

export const BRAND_LOGOS: Record<string, BrandLogo> = Object.fromEntries(
  ([
${entries}
  ] as BrandLogo[]).map((logo) => [logo.slug, logo]),
);
`,
  "utf8",
);

console.log(`Wrote ${WANTED.length} marks to ${OUT}`);
